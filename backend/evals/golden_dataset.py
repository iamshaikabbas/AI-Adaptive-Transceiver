def compute_md5(file_path: Path) -> str:
    """Compute MD5 checksum of a file."""
    h = hashlib.md5()
    with open(file_path, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


def verify_checksum(expected: str = _EXPECTED_MD5) -> tuple[bool, str]:
    """Verify the Golden Dataset checksum. Returns (ok, actual_md5)."""
    if not _GOLDEN_CSV.exists():
        return False, "FILE_NOT_FOUND"
    actual = compute_md5(_GOLDEN_CSV)
    return actual == expected, actual


class GoldenDataset:
    """Read-only loader for the Golden Dataset (final_dataset.csv).

    Loads the dataset into memory for evaluation case generation.
    Does NOT modify the source file.
    """

    def __init__(self):
        self._loaded = False
        self._rows: list[dict[str, Any]] = []
        self._grouped: dict[tuple[str, int], dict[str, dict]] = {}
        self._group_keys: list[tuple[str, int]] = []
        self._columns: list[str] = []
        self._manifest: Optional[GoldenDatasetManifest] = None
        self._load()

    def _load(self):
        """Load the golden dataset CSV."""
        if not _GOLDEN_CSV.exists():
            raise FileNotFoundError(f"Golden Dataset not found: {_GOLDEN_CSV}")

        with open(_GOLDEN_CSV, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            self._columns = reader.fieldnames or []
            for raw_row in reader:
                row = dict(raw_row)
                self._rows.append(row)
                key = (row["scenario_id"], int(row["frame"]))
                if key not in self._grouped:
                    self._grouped[key] = {}
                    self._group_keys.append(key)
                self._grouped[key][row["strategy"]] = row

        self._group_keys.sort()
        self._loaded = True
        logger.info("Golden Dataset loaded: %d rows, %d groups", len(self._rows), len(self._group_keys))

    def build_manifest(self) -> GoldenDatasetManifest:
        """Build and cache the manifest."""
        if self._manifest is not None:
            return self._manifest

        ok, actual_md5 = verify_checksum()

        scenarios = sorted(set(r["scenario_id"] for r in self._rows))
        strategies = sorted(set(r["strategy"] for r in self._rows))
        environments = sorted(set(r["environment"] for r in self._rows))
        channel_profiles = sorted(set(r["channel_profile"] for r in self._rows))
        modulations = sorted(set(int(float(r["modulation"])) for r in self._rows))
        waveform_types = sorted(set(r["waveform"] for r in self._rows if r.get("waveform")))

        snr_vals = [float(r["snr_db"]) for r in self._rows if r.get("snr_db")]
        speed_vals = [float(r["speed_kmph"]) for r in self._rows if r.get("speed_kmph")]
        doppler_vals = [float(r["doppler_hz"]) for r in self._rows if r.get("doppler_hz")]

        self._manifest = GoldenDatasetManifest(
            source_path=str(_GOLDEN_CSV),
            row_count=len(self._rows),
            column_count=len(self._columns),
            columns=list(self._columns),
            scenario_count=len(scenarios),
            scenario_ids=scenarios,
            strategies=strategies,
            environments=environments,
            channel_profiles=channel_profiles,
            modulations=modulations,
            waveform_types=waveform_types,
            snr_range=[min(snr_vals), max(snr_vals)] if snr_vals else [0, 0],
            speed_range=[min(speed_vals), max(speed_vals)] if speed_vals else [0, 0],
            doppler_range=[min(doppler_vals), max(doppler_vals)] if doppler_vals else [0, 0],
            checksum_md5=actual_md5,
            checksum_verified=ok,
            policy_version="phase3",
        )
        return self._manifest

    @property
    def rows(self) -> list[dict[str, Any]]:
        return self._rows

    @property
    def group_keys(self) -> list[tuple[str, int]]:
        return self._group_keys

    @property
    def grouped(self) -> dict[tuple[str, int], dict[str, dict]]:
        return self._grouped

    @property
    def columns(self) -> list[str]:
        return self._columns

    @property
    def manifest(self) -> GoldenDatasetManifest:
        return self.build_manifest()

    def get_fixed_otfs_rows(self) -> list[dict[str, Any]]:
        """Return all fixed_otfs rows — measured OTFS simulation results."""
        return [r for r in self._rows if r.get("strategy") == "fixed_otfs"]

    def get_fixed_oddm_rows(self) -> list[dict[str, Any]]:
        """Return all fixed_oddm rows — measured ODDM simulation results."""
        return [r for r in self._rows if r.get("strategy") == "fixed_oddm"]

    def get_oracle_rows(self) -> list[dict[str, Any]]:
        """Return all oracle rows — reference best-possible values."""
        return [r for r in self._rows if r.get("strategy") == "oracle"]

    def get_ai_adaptive_rows(self) -> list[dict[str, Any]]:
        """Return all ai_adaptive rows — AI system outputs."""
        return [r for r in self._rows if r.get("strategy") == "ai_adaptive"]

    def get_group(self, scenario_id: str, frame: int) -> dict[str, dict]:
        """Get all strategy rows for a specific (scenario_id, frame) group."""
        return self._grouped.get((scenario_id, frame), {})

    def find_exact_match(self, environment: str, speed_kmph: float, snr_db: float,
                         channel_profile: str, modulation: int) -> Optional[dict[str, Any]]:
        """Find an exact match in fixed_otfs rows by operating conditions."""
        for row in self._rows:
            if (row.get("strategy") == "fixed_otfs"
                    and row.get("environment") == environment
                    and abs(float(row.get("speed_kmph", -999)) - speed_kmph) < 1e-6
                    and abs(float(row.get("snr_db", -999)) - snr_db) < 1e-6
                    and row.get("channel_profile") == channel_profile
                    and int(float(row.get("modulation", 0))) == modulation):
                return row
        return None

    def get_domain_boundaries(self) -> dict[str, Any]:
        """Compute actual domain boundaries from the dataset."""
        if not self._rows:
            return {}

        snr_vals = [float(r["snr_db"]) for r in self._rows if r.get("snr_db")]
        speed_vals = [float(r["speed_kmph"]) for r in self._rows if r.get("speed_kmph")]
        doppler_vals = [float(r["doppler_hz"]) for r in self._rows if r.get("doppler_hz")]

        return {
            "snr_db": {"min": min(snr_vals), "max": max(snr_vals)},
            "speed_kmph": {"min": min(speed_vals), "max": max(speed_vals)},
            "doppler_hz": {"min": min(doppler_vals), "max": max(doppler_vals)},
            "environments": sorted(set(r["environment"] for r in self._rows)),
            "channel_profiles": sorted(set(r["channel_profile"] for r in self._rows)),
            "modulations": sorted(set(int(float(r["modulation"])) for r in self._rows)),
        }


def get_golden_dataset() -> GoldenDataset:
    """Singleton accessor for the Golden Dataset."""
    if not hasattr(get_golden_dataset, "_instance"):
        get_golden_dataset._instance = GoldenDataset()
    return get_golden_dataset._instance
