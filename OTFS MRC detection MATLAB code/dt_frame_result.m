function r = dt_frame_result(state)
% =========================================================================
% DT_FRAME_RESULT   Canonical RESULT template for one executed frame
% (spec section 4: a result describes WHAT HAPPENED; the state describes
% WHAT CONDITIONS EXIST -- never mix them).
%
%   r = dt_frame_result(state);   % NaN-initialized, state echo attached
%
% Metric definitions (single source of truth = MATLAB simulation chain):
%   BER/SER/PER        measured error ratios of the executed frame
%   throughput_bps     information bits / frame duration
%   spectral_efficiency bits/s/Hz
%   CQI                channel quality indicator (0-15)
%   wall_clock_ms      MEASURED outer compute time of the whole execution
%                      call (machine-dependent, NOT a communication
%                      property)
%   detector_time_ms   MEASURED inner detection time reported by the
%                      validated sim chain itself (legacy 'Latency_ms'
%                      column of Phase 2-4 traces; THIS value feeds the
%                      ACS latency term -- keep paired with it)
%   latency_ms         MODELED communication latency -- NOT modeled in the
%                      current software chain => NaN by definition. See
%                      PHASE5_ARCHITECTURE.md sec. 12.
%   packet_loss        PER-derived lost-packet ratio
%   recovery_rate      recovery heuristic from the shared metric code
%   ACS                Adaptive Communication Score via compute_acs.m
%                      (THE canonical implementation; acs.py mirrors it
%                      only for offline analysis)
% =========================================================================
r = struct( ...
    'scenario_id',       string(state.scenario_id), ...
    'frame',             int64(state.frame), ...
    'waveform',          string(state.waveform), ...
    'detector',          string(state.detector), ...
    'strategy',          string(""), ...
    'BER',               NaN, ...
    'SER',               NaN, ...
    'PER',               NaN, ...
    'throughput_bps',    NaN, ...
    'spectral_efficiency', NaN, ...
    'CQI',               NaN, ...
    'latency_ms_modeled', NaN, ...           % always NaN (not modeled)
    'wall_clock_ms',     NaN, ...            % measured outer exec time
    'detector_time_ms',  NaN, ...            % measured inner (feeds ACS)
    'packet_loss',       NaN, ...
    'recovery_rate',     NaN, ...
    'ACS',               NaN, ...
    'tp_cap_bps',        NaN, ...            % ACS normalization caps used
    'se_cap',            NaN, ...
    'error_flag',        false, ...
    'error_message',     string(""));
end
